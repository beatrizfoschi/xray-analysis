    two_theta = float(two_theta_from_direction(pixel_to_direction(col, row, GEOM)))
    theta = theta_from_G(G_magnitude(*HKL, GAN_A, GAN_C), LAM)
    assert two_theta == pytest.approx(2.0 * math.degrees(theta), abs=1e-3)

    peaks, _ = _synthetic_pixel_peaks(LAMBDA_TRUE, UB)
    p2d = {p['order']: p['position_2d'] for p in peaks}
    sep = math.hypot(p2d[1][0] - p2d[0][0], p2d[1][1] - p2d[0][1])
    assert 1.0 < sep < BOXSIZE


