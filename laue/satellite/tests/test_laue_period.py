def test_B_matrix_and_UB_composition():
    B = B_matrix_hexagonal(GAN_A, GAN_C)
    hkl = np.array(HKL, dtype=float)
    G_crystal = B @ hkl

    assert np.linalg.norm(G_crystal) == pytest.approx(6.47205, rel=1e-5)
    assert G_crystal[0] == pytest.approx(2.27507, rel=1e-5)
    assert G_crystal[1] == pytest.approx(0.0, abs=1e-12)
    assert G_crystal[2] == pytest.approx(6.05900, rel=1e-5)

    gamma_crystal = gamma_from_vectors(G_crystal, np.array([0.0, 0.0, 1.0]))
    assert math.degrees(gamma_crystal) == pytest.approx(20.5804, abs=1e-4)

    UB = _make_UB(0.0)
    assert np.linalg.det(UB) == pytest.approx(1.0, abs=1e-9)
    assert UB @ UB.T == pytest.approx(np.eye(3), abs=1e-9)

    G_lab, z_lab = lab_vectors_from_UB(HKL, (GAN_A, GAN_C), UB)
    assert np.linalg.norm(G_lab) == pytest.approx(np.linalg.norm(G_crystal), rel=1e-6)

    gamma_lab = gamma_from_vectors(G_lab, z_lab)
    assert math.degrees(gamma_lab) == pytest.approx(math.degrees(gamma_crystal), abs=1e-5)


