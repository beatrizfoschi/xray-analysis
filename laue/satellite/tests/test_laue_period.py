def test_laue_forward_period_never_uses_the_order_zero_peak():
    """Λ comes from satellite-satellite pairs only.

    The order-0 peak is the bulk reflection in an MQW (§4.13), so letting it
    into the fit would put a non-superlattice feature in the period. Moving it
    anywhere must therefore leave Λ untouched — it may only affect
    `parent_offset_deg`, which is a UB/calibration diagnostic.
    """
    UB = _make_UB(45.0)
    peaks, crop_origin = _synthetic_pixel_peaks(LAMBDA_TRUE, UB)
    kw = dict(wavelength_angstrom=LAM, method='laue_forward', hkl=HKL,
              lattice=(GAN_A, GAN_C), detector=GEOM, UB=UB,
              crop_origin_px=crop_origin)

    res = layer_period_from_peaks(peaks, **kw)
    assert all(0 not in pair['orders'] for pair in res['per_pair'])

    displaced = []
    for pk in peaks:
        pk = dict(pk)
        if pk['order'] == 0:
            r, c = pk['position_2d']
            pk['position_2d'] = (r + 7.0, c + 7.0)
            pk['pos_along_axis'] = pk['pos_along_axis'] + 7.0
        displaced.append(pk)

    assert layer_period_from_peaks(displaced, **kw)['period_angstrom'] == pytest.approx(
        res['period_angstrom'], rel=1e-12)


@pytest.mark.parametrize('spin_deg', [0.0, 45.0, 90.0, 137.0])
def test_synthetic_geometry_is_physical(spin_deg):
    """The fixture must be self-consistent, or the round trip tests nothing.

    The parent spot has to land on the frame and at the 2θ that indexing implies
    for λ = 0.727 Å; the spin must actually move the satellites, otherwise the
    orientation sweep is vacuous.
    """
    UB = _make_UB(spin_deg)
    G_lab, _ = lab_vectors_from_UB(HKL, (GAN_A, GAN_C), UB)
