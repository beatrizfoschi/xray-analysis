# ── SL0 on a two-sided train (2026-08-19) ────────────────────────────────────
#
# Real case, S100, one reflection out of three: Λ came out healthy (10.81 nm)
# while SL0 was placed at -21.21 px, on top of SL-2 at -21.74.  Λ never uses SL0,
# so the period could not warn about it — the marker landing in an absurd place
# was the only symptom.  Cause: with satellites on BOTH sides of the parent the
# two innermost are -1 and +1, and inferring the step direction from their
# ordering inverts it, walking SL0 one order outward instead of inward.

S100_AXIS_DEG = -71.02
S100_CENTRE = (16.0, 42.0)
S100_LADDER = [(-3, -31.87), (-2, -21.74), (-1, -11.36),
               (0, +0.12), (1, +8.94), (2, +16.65)]


def _two_sided_peaks(ladder=S100_LADDER, axis_deg=S100_AXIS_DEG):
    rad = math.radians(axis_deg)
    cr, cc = S100_CENTRE
    return [{'order': n, 'pos_along_axis': s, 'amplitude': 1.0, 'fwhm': 2.0,
             'sigma': 0.85,
             'position_2d': (cr + s * math.sin(rad), cc + s * math.cos(rad))}
            for n, s in ladder]


def _two_sided_kwargs():
    return dict(hkl=HKL, lattice=(GAN_A, GAN_C),
                UB=ub_from_beam_x_frame(MQW15_UB_RAW), detector=MQW15_GEOM,
                crop_origin_px=(1905, 572), period_angstrom=108.1)


def test_sl0_on_a_two_sided_train_lands_near_the_parent():
    res = locate_sl0_from_ladder(_two_sided_peaks(), **_two_sided_kwargs())
    sl0 = res['sl0_pos_along_axis']
    # Within one step of the parent at +0.12, not one step the other way.
    assert abs(sl0 - 0.12) < res['gap_pred_px']
    # And nowhere near SL-2, which is where the inverted step used to put it.
    assert abs(sl0 - (-21.74)) > 10.0


def test_extra_positive_orders_do_not_move_sl0():
    """Adding satellites on the far side must not change the prediction."""
    kw = _two_sided_kwargs()
    both = locate_sl0_from_ladder(_two_sided_peaks(), **kw)
    neg  = locate_sl0_from_ladder(
        [p for p in _two_sided_peaks() if p['order'] <= 0], **kw)
    assert both['sl0_pos_along_axis'] == pytest.approx(
        neg['sl0_pos_along_axis'], abs=1e-9)


def test_sl0_scale_pair_stays_on_one_side():
    """The local scale must not use a baseline that straddles the parent."""
    res = locate_sl0_from_ladder(_two_sided_peaks(), **_two_sided_kwargs())
    # -1 -> -2 is 10.38 px; -1 -> +1 would be 20.30 px and cross the bulk.
    assert res['gap_meas_px'] == pytest.approx(10.38, abs=0.01)


def test_sl0_direction_survives_a_reversed_train():
    """Position may increase or decrease with order; only the trend decides."""
    mirrored = [(n, -s) for n, s in S100_LADDER]
    res = locate_sl0_from_ladder(_two_sided_peaks(ladder=mirrored),
                                 **_two_sided_kwargs())
    assert abs(res['sl0_pos_along_axis'] - (-0.12)) < res['gap_pred_px']
    assert abs(res['sl0_pos_along_axis'] - (+21.74)) > 10.0


# ── Order-label sign resolved against the model (§4.11.2) ────────────────────
#
# Detection's +n is a detector-space convention with no crystallographic
# reference, so it is inverted for some reflections.  The period announces it by
# railing against a bound; the asymmetry indicators would not — they would simply
# come out with the opposite sign.

def _sign_kwargs():
    return dict(hkl=HKL, lattice=MLED_LATTICE,
                UB=ub_from_beam_x_frame(UB_MLED_RAW), detector=MLED_GEOM,
                crop_origin_px=MLED_CROP_ORIGIN)


def test_correct_labels_are_left_alone():
    res = resolve_order_sign(_mled_peaks(), **_sign_kwargs())
    assert res['confident']
    assert not res['inverted']
    assert res['arrow_cos'] > 0.99


def test_inverted_labels_are_detected():
    flipped = [dict(p, order=-p['order']) for p in _mled_peaks()]
    res = resolve_order_sign(flipped, **_sign_kwargs())
    assert res['confident']
    assert res['inverted']
    assert res['arrow_cos'] < -0.99


def test_correction_makes_the_two_labellings_agree():
    """The point of the fix: the same image gives the same Λ either way."""
    kw = _sign_kwargs()
    flipped = [dict(p, order=-p['order']) for p in _mled_peaks()]
    a, _ = resolve_and_apply_order_sign(_mled_peaks(), **kw)
    b, _ = resolve_and_apply_order_sign(flipped, **kw)
    assert sorted(p['order'] for p in a) == sorted(p['order'] for p in b)
    p_a = layer_period_from_peaks(a, method='laue_forward',
                                  wavelength_angstrom=0.7267, **kw)
    p_b = layer_period_from_peaks(b, method='laue_forward',
                                  wavelength_angstrom=0.7267, **kw)
    assert p_a['period_nm'] == pytest.approx(p_b['period_nm'], rel=1e-12)
    assert not p_a['fit_at_bound'] and not p_b['fit_at_bound']


def test_signed_metrics_follow_the_correction():
    """Why the fix lives above the metrics rather than inside the period route.

    `delta_q` is signed, and so are the asymmetry indicators when both sides are
    present.  An inverted label set flips them with no warning of any kind — the
    period at least announces itself by railing against a bound.
    """
    from laue.satellite.metrics import compute_metrics
    kw = _sign_kwargs()
    flipped = [dict(p, order=-p['order']) for p in _mled_peaks()]

    truth = compute_metrics(_mled_peaks())
    raw   = compute_metrics(flipped)
    fixed = compute_metrics(resolve_and_apply_order_sign(flipped, **kw)[0])

    assert raw['delta_q'] == pytest.approx(-truth['delta_q'])    # silent flip
    for key in ('delta_q', 'n_sat', 'bulk_pos', 'alpha'):
        assert fixed[key] == pytest.approx(truth[key])           # correction undoes it


def test_a_wrong_ub_frame_refuses_to_decide_the_sign():
    """Gate 1: an orientation that does not point here has no authority."""
    kw = _sign_kwargs()
    kw['UB'] = UB_MLED_RAW.T            # a plausible-looking but wrong frame
    res = resolve_order_sign(_mled_peaks(), **kw)
    assert not res['confident']
    assert not res['inverted']
    assert 'parent_offset' in res['reason']


def test_a_train_off_the_predicted_line_refuses_to_decide_the_sign():
    """Gate 2: with the line wrong, the arrow question does not apply."""
    peaks = _mled_peaks()
    parent = next(p for p in peaks if p['order'] == 0)
    pr, pc = parent['position_2d']
    t = math.radians(40.0)
    rotated = []
    for p in peaks:                      # rotate the satellites about the parent
        if p['order'] == 0:
            rotated.append(p)
            continue
        dr, dc = p['position_2d'][0] - pr, p['position_2d'][1] - pc
        rotated.append(dict(p, position_2d=(
            pr + dr * math.cos(t) - dc * math.sin(t),
            pc + dr * math.sin(t) + dc * math.cos(t))))
    res = resolve_order_sign(rotated, **_sign_kwargs())
    assert res['parent_offset_deg'] < 1.0      # gate 1 still passes
    assert not res['confident']
    assert 'train_delta' in res['reason']


