# ── ADDENDUM 2 §5.3 — separation methods against fixtures ───────────────────

def _train_geometry(phi_deg: float):
    """Satellite (2θ, χ) for orders 0..3 with the train at a chosen orientation.

    φ = 0 puts the train radial, φ = 90° azimuthal — the two extremes of §2.
    """
    gamma = gamma_from_hkl(*HKL, GAN_A, GAN_C)
    G_mag = G_magnitude(*HKL, GAN_A, GAN_C)
    theta = theta_from_G(G_mag, LAM)
    az = math.radians(75.0)
    G0h = np.array([math.cos(theta) * math.cos(az), -math.sin(theta),
                    math.cos(theta) * math.sin(az)])

    p = LAB_KI - (LAB_KI @ G0h) * G0h
    p /= np.linalg.norm(p)
    q = np.cross(G0h, p)

    phi = math.radians(phi_deg)
    e_in = math.cos(phi) * p - math.sin(phi) * q
    z_lab = math.cos(gamma) * G0h + math.sin(gamma) * e_in
    return predict_satellite_angles(G_mag * G0h, z_lab, LAMBDA_TRUE, (0, 1, 2, 3))


@pytest.mark.parametrize('phi_deg, expected_deg', [
    (0.0,  0.399411),     # radial
    (45.0, 0.301574),
    (90.0, 0.149550),     # azimuthal
])
def test_separation_methods_against_fixtures(phi_deg, expected_deg):
    tt, chi = _train_geometry(phi_deg)
    exact = math.degrees(float(angular_separation(tt[0], chi[0], tt[1], chi[1])))
    # abs=1e-6, not rel: the spec quotes these to six decimals, so a tighter
    # tolerance would only be testing the rounding of the fixture.
    assert exact == pytest.approx(expected_deg, abs=1e-6)

    # Weighted quadrature is the correct local metric and must track the exact
    # value; naive quadrature and Δ(2θ)-only must not.
    d_tt  = abs(tt[1] - tt[0])
    d_chi = abs(chi[1] - chi[0])
    weighted = math.hypot(d_tt, math.sin(math.radians(tt[0])) * d_chi)
    assert weighted == pytest.approx(exact, rel=5e-4)


@pytest.mark.parametrize('phi_deg, d2theta_only, naive', [
    (0.0,  0.399411, 0.399411),
    (45.0, 0.282566, 0.320921),
    (90.0, 0.000281, 0.215372),
])
def test_documented_failure_modes(phi_deg, d2theta_only, naive):
    """Documents the failure modes rather than permitting them.

    Δ(2θ) alone collapses to 0.000281° against a true 0.149550° when the train is
    azimuthal — it would report no separation where a clear one exists.  Naive
    quadrature overshoots by +44 % in the same case.
    """
    tt, chi = _train_geometry(phi_deg)
    d_tt  = abs(tt[1] - tt[0])
    d_chi = abs(chi[1] - chi[0])
    assert d_tt == pytest.approx(d2theta_only, abs=1e-5)
    assert math.hypot(d_tt, d_chi) == pytest.approx(naive, abs=1e-5)


def test_nonuniform_spacing_survives_train_orientation():
    """The 1.8 %/step contraction is the discriminating signature and is intrinsic."""
    for phi_deg in (0.0, 45.0, 90.0):
        tt, chi = _train_geometry(phi_deg)
        seps = np.array([float(angular_separation(tt[k], chi[k], tt[k+1], chi[k+1]))
                         for k in range(3)])
        ratios = seps / seps[0]
        assert ratios[1] == pytest.approx(0.9816, abs=0.001)
        assert ratios[2] == pytest.approx(0.9636, abs=0.001)


