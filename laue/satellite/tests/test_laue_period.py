# ── Rotation helpers, for building synthetic orientations ────────────────────

def _rodrigues(axis, angle_rad):
    axis = np.asarray(axis, dtype=float)
    axis = axis / np.linalg.norm(axis)
    K = np.array([[0.0, -axis[2], axis[1]],
                  [axis[2], 0.0, -axis[0]],
                  [-axis[1], axis[0], 0.0]])
    return np.eye(3) + math.sin(angle_rad) * K + (1 - math.cos(angle_rad)) * (K @ K)


def _rot_between(v1, v2):
    """Minimal rotation taking unit v1 onto unit v2."""
    v1 = np.asarray(v1, float) / np.linalg.norm(v1)
    v2 = np.asarray(v2, float) / np.linalg.norm(v2)
    axis = np.cross(v1, v2)
    n = np.linalg.norm(axis)
    if n < 1e-14:
        return np.eye(3) if v1 @ v2 > 0 else -np.eye(3)
    return _rodrigues(axis, math.acos(np.clip(v1 @ v2, -1.0, 1.0)))


def _make_UB(spin_deg: float, azimuth_deg: float = 75.0):
    """A physically consistent UB for the (105) parent reflection at λ = 0.727 Å.

    The plane normal is placed at the Bragg angle to the beam, û·Ĝ = −sin θ, so
    the resulting spot sits at 2θ = 2·arcsin(|G|λ/4π) by construction and the
    pixel position is an OUTPUT.  Placing the spot at an arbitrary pixel instead
    would silently imply a different wavelength — in Laue the spot position is
    fixed by the direction of Ĝ, and λ adjusts to satisfy Bragg.

    ``azimuth_deg`` rotates Ĝ about the beam (moving the spot across the frame);
    ``spin_deg`` rotates the crystal about Ĝ, leaving the parent spot fixed.  The
    latter is the residual freedom the parent spec swept as φ, and varying it is
    what catches convention inversions.
    """
    theta = theta_from_G(G_magnitude(*HKL, GAN_A, GAN_C), LAM)
    a = math.radians(azimuth_deg)
    G_dir = np.array([math.cos(theta) * math.cos(a),
                      -math.sin(theta),
                      math.cos(theta) * math.sin(a)])

    B = B_matrix_hexagonal(GAN_A, GAN_C)
    G_crystal = B @ np.array(HKL, dtype=float)
    G_crystal_hat = G_crystal / np.linalg.norm(G_crystal)

    return _rodrigues(G_dir, math.radians(spin_deg)) @ _rot_between(G_crystal_hat, G_dir)


def _peak(order, pos_along_axis, position_2d=None):
    p = {'order': order, 'pos_along_axis': pos_along_axis,
         'amplitude': 100.0, 'fwhm': 4.0, 'sigma': 1.7}
    if position_2d is not None:
        p['position_2d'] = position_2d
    return p


def _synthetic_pixel_peaks(period_angstrom, UB, orders=range(-3, 4)):
    """Peaks generated by the exact pixel-space forward model, in crop coordinates."""
    orders = list(orders)
    G_lab, z_lab = lab_vectors_from_UB(HKL, (GAN_A, GAN_C), UB)
    col, row = predict_satellite_pixels(G_lab, z_lab, period_angstrom, orders, GEOM)
    col, row = np.asarray(col), np.asarray(row)

    # The crop is centred on the parent spot, whose position is an output of the
    # model — not a value chosen in advance (see _make_UB).
    parent_col, parent_row = direction_to_pixel(kf_hat(G_lab, LAB_KI), GEOM)
    row0, col0 = parent_row - BOXSIZE, parent_col - BOXSIZE
    axis = np.array([col[-1] - col[0], row[-1] - row[0]])
    axis = axis / np.linalg.norm(axis)
    zero = orders.index(0) if 0 in orders else 0

    peaks = []
    for n, cc, rr in zip(orders, col, row):
        s = float(np.array([cc - col[zero], rr - row[zero]]) @ axis)
        peaks.append(_peak(n, s, position_2d=(rr - row0, cc - col0)))
    return peaks, (row0, col0)


