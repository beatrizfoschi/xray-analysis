def test_two_theta_measured_is_the_parent_not_the_satellite_mean():
    """The satellites sit along the train, so their mean 2θ is offset by design.

    Reporting that mean as `two_theta_measured` made a correct dataset look like
    it disagreed with indexing by ~1°.  The comparable quantity is the parent's.
    """
    UB = _make_UB(90.0)          # spin 90: the train is mostly radial here
    peaks, crop_origin = _synthetic_pixel_peaks(LAMBDA_TRUE, UB, orders=[-3, -2, -1, 0])
    row0, col0 = crop_origin
    res = layer_period_from_peaks(
        peaks, wavelength_angstrom=LAM, method='laue_forward',
        hkl=HKL, lattice=(GAN_A, GAN_C),
        detector=GEOM, UB=UB, crop_origin_px=crop_origin,
    )

    # two_theta_measured must be the parent's own 2θ, computed independently.
    parent = next(p for p in peaks if p['order'] == 0)
    tt_parent, _ = pixels_to_2theta_chi(col0 + parent['position_2d'][1],
                                        row0 + parent['position_2d'][0], GEOM)
    assert res['two_theta_measured'] == pytest.approx(float(tt_parent[0]), abs=1e-9)
    assert res['two_theta_measured'] == pytest.approx(res['two_theta_deg'], abs=0.05)

    # two_theta_satellites is the mean over the satellite orders — a different
    # quantity, and the one that must NOT be compared against indexing.
    sats = [p for p in peaks if p['order'] != 0]
    tt_s, _ = pixels_to_2theta_chi(
        [col0 + p['position_2d'][1] for p in sats],
        [row0 + p['position_2d'][0] for p in sats], GEOM)
    assert res['two_theta_satellites'] == pytest.approx(float(np.mean(tt_s)), abs=1e-9)
    assert res['two_theta_satellites'] != pytest.approx(res['two_theta_measured'],
                                                        abs=0.1)


