def _displace_order0(peaks, fraction):
    """Move the order-0 peak by `fraction` of one step, along the train."""
    p0 = next(p for p in peaks if p['order'] == 0)
    p1 = min((p for p in peaks if p['order'] != 0), key=lambda p: abs(p['order']))
    d_pos = p1['pos_along_axis'] - p0['pos_along_axis']
    d_row = p1['position_2d'][0] - p0['position_2d'][0]
    d_col = p1['position_2d'][1] - p0['position_2d'][1]
    out = []
    for p in peaks:
        q = dict(p)
        if q['order'] == 0:
            q['pos_along_axis'] = p0['pos_along_axis'] + fraction * d_pos
            q['position_2d'] = (p0['position_2d'][0] + fraction * d_row,
                                p0['position_2d'][1] + fraction * d_col)
        out.append(q)
    return out


