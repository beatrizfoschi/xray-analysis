def test_half_step_is_never_reported_as_a_hidden_order():
    """A hidden order displaces by a WHOLE step; half a step is a different fault.

    Guards the specific misreading that produced the original wrong diagnosis.
    """
    UB = _make_UB(90.0)
    peaks, crop_origin = _synthetic_pixel_peaks(LAMBDA_TRUE, UB, orders=[-3, -2, -1, 0])
    kw = dict(hkl=HKL, lattice=(GAN_A, GAN_C), UB=UB, detector=GEOM,
              crop_origin_px=crop_origin, period_angstrom=LAMBDA_TRUE, verbose=False)

    for fraction in (0.4, 0.5, 0.6, 1.5):
        res = check_order_assignment(_displace_order0(peaks, fraction), **kw)
        assert res['verdict'] == 'order0_off_ladder', f'fraction={fraction}'
