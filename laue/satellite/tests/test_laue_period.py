# ── §4.5 — the analytic route's known bias ───────────────────────────────────

def _first_pair_peaks(phi_deg: float):
    """Two peaks carrying the 0→1 model separation, for the analytic route.

    The analytic route derives Λ from a single Δψ and is order-agnostic, so the
    0→1 separation rides on labels (1, 2) — the period routes exclude any pair
    touching SL0, whose fitted position is contaminated by the bulk Bragg peak.
    """
    gamma = gamma_from_hkl(*HKL, GAN_A, GAN_C)
    G_mag = G_magnitude(*HKL, GAN_A, GAN_C)
    theta = theta_from_G(G_mag, LAM)
    G0_hat, z_lab, u_hat = build_canonical_frame(gamma, theta, math.radians(phi_deg))
    sep = predict_angular_separations(G_mag * G0_hat, z_lab, LAMBDA_TRUE, (0, 1), u_hat)[0]
    two_theta = 2.0 * math.degrees(theta)
    dx = float(sep) * 200.0 / (0.075 * math.cos(math.radians(two_theta)) ** 2)
    return [_peak(1, 0.0), _peak(2, dx)]


def test_analytic_route_matches_known_bias():
    """Pins the +0.94 % small-angle bias so a future change is flagged, not absorbed."""
    res = layer_period_from_peaks(
        _first_pair_peaks(0.0),
        pixel_size_mm=0.075, detector_distance_mm=200.0,
        wavelength_angstrom=LAM, method='laue_analytic',
        hkl=HKL, lattice=(GAN_A, GAN_C), phi_deg=0.0, satellite_axis_psi_deg=0.0,
    )
    assert res['period_angstrom'] == pytest.approx(97.909, abs=0.01)
    assert res['method'] == 'laue_analytic'


