    rad = math.radians(MLED_AXIS_DEG)
    cr = MLED_BOX + sl0_center_offset_px * math.sin(rad)
    cc = MLED_BOX + sl0_center_offset_px * math.cos(rad)
    return [{'order': n, 'pos_along_axis': s, 'amplitude': a,
             'fwhm': 2.5, 'sigma': 2.5 / 2.3548,
             'position_2d': (cr + s * math.sin(rad), cc + s * math.cos(rad))}
            for n, s, a in MLED_REAL_PEAKS]


